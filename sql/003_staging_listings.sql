CREATE TABLE IF NOT EXISTS staging.listings (
    source              TEXT             NOT NULL,
    listing_id          TEXT             NOT NULL,
    snapshot_date       DATE             NOT NULL,
    title               TEXT,
    price_raw           TEXT,
    price_vnd           NUMERIC,
    original_price_vnd  NUMERIC,
    area_m2             NUMERIC,
    property_type       TEXT,
    province_raw        TEXT,
    district_raw        TEXT,
    ward_raw            TEXT,
    street_raw          TEXT,
    latitude            DOUBLE PRECISION,
    longitude           DOUBLE PRECISION,
    deposit_vnd         NUMERIC,
    posted_at           TIMESTAMPTZ,
    posted_date         DATE,
    batch_id            TEXT             NOT NULL,
    bronze_key          TEXT             NOT NULL,
    loaded_at           TIMESTAMPTZ      NOT NULL DEFAULT now(),
    PRIMARY KEY (source, listing_id, snapshot_date)
);